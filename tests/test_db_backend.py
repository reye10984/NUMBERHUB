import sqlite3
from unittest import TestCase, mock

import psycopg
from psycopg import errors

from db_backend import PostgresConnection, HybridRow


class FakeConnection:
    def __init__(self):
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((sql, params))
        return "fake-cursor"


class DatabaseBackendTests(TestCase):
    def test_sql_converts_placeholders(self):
        sql = PostgresConnection._sql(
            "SELECT id FROM users WHERE email=? AND referral_code=?"
        )
        self.assertEqual(
            sql,
            "SELECT id FROM users WHERE email=%s AND referral_code=%s",
        )

    def test_sql_converts_begin_immediate(self):
        self.assertEqual(
            PostgresConnection._sql("BEGIN IMMEDIATE"),
            "BEGIN",
        )

    def test_sql_converts_integer_primary_key(self):
        sql = PostgresConnection._sql(
            "CREATE TABLE sample (id INTEGER PRIMARY KEY)"
        )
        self.assertIn(
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            sql,
        )

    def test_execute_passes_converted_sql_and_parameters(self):
        connection = FakeConnection()
        adapter = PostgresConnection(connection)

        result = adapter.execute(
            "SELECT id FROM users WHERE email=?",
            ("test@example.com",),
        )

        self.assertEqual(result, "fake-cursor")
        self.assertEqual(
            connection.calls,
            [("SELECT id FROM users WHERE email=%s", ("test@example.com",))],
        )

    def test_hybrid_row_supports_names_and_indexes(self):
        row = HybridRow(["id", "email"], [7, "test@example.com"])

        self.assertEqual(row["id"], 7)
        self.assertEqual(row["email"], "test@example.com")
        self.assertEqual(row[0], 7)
        self.assertEqual(row[1], "test@example.com")

    def test_unique_violation_becomes_integrity_error(self):
        original = errors.UniqueViolation("duplicate key")

        with mock.patch.object(
            PostgresConnection,
            "_raise_compatible_error",
            wraps=PostgresConnection._raise_compatible_error,
        ):
            with self.assertRaises(sqlite3.IntegrityError):
                PostgresConnection._raise_compatible_error(original)

    def test_other_postgres_error_becomes_sqlite_error(self):
        original = errors.SyntaxError("invalid SQL")

        with self.assertRaises(sqlite3.Error):
            PostgresConnection._raise_compatible_error(original)
