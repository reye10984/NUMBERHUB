"""SQLite/PostgreSQL compatibility layer for NumberHub."""
import re
import sqlite3


class HybridRow:
    """A database row supporting both row['name'] and row[0]."""

    def __init__(self, names, values):
        self._names = list(names)
        self._values = tuple(values)
        self._mapping = dict(zip(self._names, self._values))

    def __getitem__(self, key):
        if isinstance(key, str):
            return self._mapping[key]
        return self._values[key]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def keys(self):
        return self._names


def _row_factory(cursor):
    description = cursor.description
    if description is None:
        return None

    names = [column.name for column in description]

    def make_row(values):
        return HybridRow(names, values)

    return make_row


class PostgresConnection:
    """Small adapter preserving the SQL interface used by NumberHub."""

    def __init__(self, connection):
        self._connection = connection

    @staticmethod
    def _sql(sql):
        sql = sql.strip()
        if sql.upper() == "BEGIN IMMEDIATE":
            sql = "BEGIN"

        # Use consistent BIGINT types for PostgreSQL IDs and integer fields.
        sql = re.sub(
            r"\bINTEGER\s+PRIMARY\s+KEY\b",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            sql,
            flags=re.IGNORECASE,
        )
        sql = re.sub(r"\bINTEGER\b", "BIGINT", sql, flags=re.IGNORECASE)

        # Existing application queries use SQLite's ? placeholders.
        sql = sql.replace("?", "%s")
        return sql

    def execute(self, sql, params=()):
        if sql.strip().upper() == "PRAGMA FOREIGN_KEYS=ON":
            return _EmptyCursor()

        try:
            return self._connection.execute(self._sql(sql), params)
        except Exception as exc:
            self._raise_compatible_error(exc)

    def executescript(self, script):
        # The application schema contains ordinary SQL statements separated
        # by semicolons, with no semicolons embedded in string literals.
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        try:
            self._connection.execute("COMMIT")
        except Exception as exc:
            self._raise_compatible_error(exc)

    def rollback(self):
        try:
            self._connection.execute("ROLLBACK")
        except Exception as exc:
            # A failed query may already have ended the transaction.
            if "no transaction" not in str(exc).lower():
                self._raise_compatible_error(exc)

    def close(self):
        self._connection.close()

    @staticmethod
    def _raise_compatible_error(exc):
        try:
            import psycopg
            from psycopg import errors
        except ImportError:
            raise exc

        if isinstance(exc, errors.UniqueViolation):
            raise sqlite3.IntegrityError(str(exc)) from exc
        if isinstance(exc, psycopg.Error):
            raise sqlite3.Error(str(exc)) from exc
        raise exc


class _EmptyCursor:
    rowcount = -1

    def fetchone(self):
        return None


def connect_postgres(database_url):
    """Connect to PostgreSQL using psycopg 3."""
    import psycopg

    connection = psycopg.connect(
        database_url,
        autocommit=True,
        row_factory=_row_factory,
        connect_timeout=15,
    )
    return PostgresConnection(connection)


def connect_database(database_url=None, sqlite_path=None):
    """Open PostgreSQL when configured; otherwise retain SQLite support."""
    if database_url:
        return connect_postgres(database_url)

    if not sqlite_path:
        raise ValueError("A SQLite database path is required.")

    connection = sqlite3.connect(sqlite_path, isolation_level=None)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys=ON")
    return connection
